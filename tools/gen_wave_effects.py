"""Generate src/wave_effects.h: which effect record each ground-wave skill puts in the world (the user, 2026-10-23).
A Skill_AttackWave (Voldrak's Groundbreaker) makes no ProjectileBase: its travelling crack is an EffectEntity named by
the skill's lineEffectName (or an FxPak by fxPakName), with no owner. The projectile cue (src/projectiles.cpp) ticks
such an effect only when it appears just after a foe cast a skill naming it -- the same effect can be a player relic's
too (groundripper_fx01 is also Conflagration's beam groundEffect). Waves without either field draw nothing that travels.
Rerun after a game patch (database.arz changes): uv run tools/gen_wave_effects.py"""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import arz

FIELDS = ("lineEffectName", "fxPakName")

def main():
    d, strings, recs = arz.load()
    rows = []
    for path, rname, off, csz, dsz in recs:
        if not path.lower().startswith("records/skills/"): continue
        m = arz.decode(d, strings, off, csz, dsz)
        if (m.get("Class") or [""])[0] != "Skill_AttackWave": continue
        for k in FIELDS:
            v = (m.get(k) or [""])[0]
            if v: rows.append((path.lower(), v.lower(), k))
    rows.sort()
    out = ["// GENERATED by tools/gen_wave_effects.py -- do not edit", "#pragma once",
           "// The effect each ground-wave skill (Skill_AttackWave) sends travelling (lineEffectName / fxPakName). Keys are",
           "// lowercase record paths.",
           "namespace gd::projectiles {",
           "struct WaveEffect { const char* skill; const char* effect; };",
           "inline constexpr WaveEffect kWaveEffects[] = {"]
    for skill, fx, k in rows:
        out.append(f'  {{"{skill}", "{fx}"}},   // {k}')
    out += ["};", "}  // namespace gd::projectiles", ""]
    dst = os.path.join(HERE, "..", "src", "wave_effects.h")
    with open(dst, "w", encoding="utf-8", newline="\n") as f: f.write("\n".join(out))
    print(f"wrote src/wave_effects.h with {len(rows)} skill/effect pairs, {len({r[1] for r in rows})} distinct effects")

if __name__ == "__main__":
    main()
