"""Generate src/telegraph_records.h: per-skill-record telegraph shapes that override the class table in
src/telegraph.cpp (telegraph::shape_of). A class says how a skill works, not always the shape a player has to avoid,
so the projectile skills are sorted by what their projectiles do (the user, 2026-10-22):
  - LOBBED first: an aimed skill (not a ring) whose projectile record has a launchAngle above zero throws it in an arc
    that lands at the point picked at cast start (the Grand Priest's fireballs, 35 degrees, ended at their aim point;
    the deathbolt, no angle, flew through it): "area", leave the spot -- like the pools and the lightning strikes;
  - a "frontal" is anything covering 90 to 180 degrees in front of the caster (at least 45 either side, at most a half
    circle: wider no longer reads as "in front" -- the user); wider than 180 is a ring;
  - a ring narrower than 90 degrees is a fan in front: "wave".
The arc is projectileLaunchRotation (fans, rings, bursts) or, for a ground wave, the angle of its sides from
waveDistance / waveStartWidth / waveEndWidth -- the widest level, since the shape at the top levels is the one met.
Rerun after a game patch (database.arz changes): uv run tools/gen_telegraph_records.py"""
import math, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import arz

FRONTAL_MIN, FRONTAL_MAX = 90.0, 180.0
DEFAULT = {"Skill_AttackProjectileRing": "ring", "Skill_AttackProjectileFan": "wave", "Skill_AttackProjectileBurst": "shot",
           "Skill_AttackWave": "wave", "Skill_AttackProjectile": "shot", "Skill_AttackProjectileDebuf": "shot"}
AIMED = {"Skill_AttackProjectile", "Skill_AttackProjectileBurst", "Skill_AttackProjectileFan", "Skill_AttackProjectileDebuf"}
ARC_CLASSES = {"Skill_AttackProjectileRing", "Skill_AttackProjectileFan", "Skill_AttackProjectileBurst", "Skill_AttackWave"}

def widest(m, k):
    v = [x for x in (m.get(k) or []) if x]
    return max(v) if v else 0.0

def arc_of(cls, m):
    if cls == "Skill_AttackWave":
        dist, w0, w1 = widest(m, "waveDistance"), widest(m, "waveStartWidth"), widest(m, "waveEndWidth")
        return 2 * math.degrees(math.atan(max(0.0, w1 - w0) / 2 / dist)) if dist else 0.0
    return widest(m, "projectileLaunchRotation")

def shape_by_arc(cls, arc):
    if arc > FRONTAL_MAX: return "ring"
    if arc >= FRONTAL_MIN: return "frontal"
    if cls == "Skill_AttackProjectileRing": return "wave"
    return DEFAULT[cls]

def main():
    d, strings, recs = arz.load()
    by_path = {r[0].lower(): r for r in recs}
    cache = {}
    def rec(path):
        p = path.lower()
        if p not in cache:
            r = by_path.get(p)
            cache[p] = arz.decode(d, strings, r[2], r[3], r[4]) if r else None
        return cache[p]
    def lobbed(m):
        for k in ("skillProjectileName", "projectileNames"):
            for x in m.get(k) or []:
                if isinstance(x, str) and x:
                    pm = rec(x)
                    if pm and widest(pm, "launchAngle") > 0: return True
        return False
    rows = []
    for r in recs:
        path = r[0].lower()
        if not path.startswith("records/skills/"): continue
        m = arz.decode(d, strings, r[2], r[3], r[4])
        cls = (m.get("Class") or [""])[0]
        if cls not in DEFAULT: continue
        if cls in AIMED and lobbed(m):
            shape, why = "area", "lobbed at a point"
        elif cls in ARC_CLASSES:
            arc = arc_of(cls, m)
            shape, why = shape_by_arc(cls, arc), f"{arc:.0f} degrees"
        else:
            continue
        if shape != DEFAULT[cls]: rows.append((path, shape, cls, why))
    rows.sort()
    out = ["// GENERATED by tools/gen_telegraph_records.py -- do not edit", "#pragma once",
           "// Per-record telegraph shapes overriding the class table (telegraph::shape_of): lobbed projectile skills, and",
           "// projectile spreads and waves sorted by their own arc. Keys are lowercase record paths.",
           "namespace gd::telegraph {",
           "struct RecordShape { const char* record; const char* shape; };",
           "inline constexpr RecordShape kRecordShapes[] = {"]
    for path, shape, cls, why in rows:
        out.append(f'  {{"{path}", "{shape}"}},   // {cls}, {why}')
    out += ["};", "}  // namespace gd::telegraph", ""]
    dst = os.path.join(HERE, "..", "src", "telegraph_records.h")
    with open(dst, "w", encoding="utf-8", newline="\n") as f: f.write("\n".join(out))
    print(f"wrote src/telegraph_records.h with {len(rows)} records")
    from collections import Counter
    print("  by shape:", dict(Counter((s, c) for _, s, c, _ in rows)))
    for path, shape, cls, why in rows:
        if "nonplayerskills" in path and shape == "area": print(f"  area   {path.split('/')[-1]}  ({cls})")

if __name__ == "__main__":
    main()
